/**
 * Chequeo de coherencia unificado para cualquier conjunto de alimentos
 * (Lote 1, Lote 2 o catalogo completo combinado).
 *
 * Formula: proteina*4 + carbohidratos*4 + grasa*9 vs kcal declaradas.
 * - Las bebidas alcoholicas estan exentas por el aporte calorico del alcohol (7 kcal/g).
 * - El vinagre esta exento porque sus calorias derivan del acido acetico (~3.5 kcal/g).
 * - En alimentos de muy bajas calorias (<20 kcal o desviacion absoluta <=10 kcal),
 *   variaciones minimas por fibra o agua no se consideran incoherencias.
 */
export function alimentosIncoherentes(
  alimentos: AlimentoSemilla[],
  tolerancia = 0.25,
): string[] {
  return alimentos
    .filter((a) => {
      if (BEBIDAS_ALCOHOLICAS_EXENTAS.has(a.nombre)) return false;
      if (a.nombre === 'Vinagre') return false;
      if (a.kcal_por_100g < 20) return false;

      const calculadas = a.proteina_g * 4 + a.carbohidratos_g * 4 + a.grasa_g * 9;
      const diffAbs = Math.abs(calculadas - a.kcal_por_100g);
      if (diffAbs <= 10) return false;

      return diffAbs / a.kcal_por_100g > tolerancia;
    })
    .map((a) => a.nombre);
}

